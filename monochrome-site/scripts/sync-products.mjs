#!/usr/bin/env node
// Refreshes data/products.js from the Shopify storefront.
// Usage: node scripts/sync-products.mjs   (Node 18+). Run it before each deploy, or on a schedule.
import { writeFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const STORE = process.env.STORE_URL || 'https://monochrome.com.ng';
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'data', 'products.js');

// Shopify Markets localises prices by visitor, so pin the request to the store's home market (Canada, CAD).
const MARKET = process.env.STORE_COUNTRY || 'CA';
const get = async path => {
  const r = await fetch(`${STORE}${path}${path.includes('?') ? '&' : '?'}country=${MARKET}`, { headers: { accept: 'application/json', 'accept-language': 'en-CA' } });
  if (!r.ok) throw new Error(`${path} -> ${r.status}`);
  return r.json();
};

const text = html => (html || '').replace(/<[^>]+>/g, ' ').replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&').replace(/\s+/g, ' ').trim();

// top / bottom / accessory drive the Fit Studio; gift is sold but never styled onto the avatar.
const category = p => {
  const s = `${p.title} ${p.product_type}`.toLowerCase();
  if (/gift/.test(s)) return 'gift';
  if (/ring|chain|necklace|jewel|accessor/.test(s)) return 'accessory';
  if (/short|skirt|pant(?!s chain)|trouser|jean/.test(s)) return 'bottom';
  return 'top';
};

const all = [];
for (let page = 1; ; page++) {
  const { products } = await get(`/products.json?limit=250&page=${page}`);
  all.push(...products);
  if (products.length < 250) break;
}
const [{ collections }, meta] = await Promise.all([get('/collections.json?limit=250'), get('/meta.json')]);

const products = all.map(p => {
  const prices = p.variants.map(v => Number(v.price)).filter(Number.isFinite);
  const sizeOpt = p.options.find(o => /size/i.test(o.name));
  return {
    handle: p.handle,
    title: p.title.trim(),
    category: category(p),
    type: p.product_type || '',
    description: text(p.body_html),
    price: Math.min(...prices),
    priceMax: Math.max(...prices),
    available: p.variants.some(v => v.available),
    sizes: sizeOpt ? sizeOpt.values : [],
    options: p.options.map(o => ({ name: o.name, values: o.values })),
    variants: p.variants.map(v => ({ id: v.id, options: [v.option1, v.option2, v.option3].filter(x => x != null), price: Number(v.price), available: v.available })),
    images: p.images.map(i => ({ src: i.src, w: i.width, h: i.height })),
    publishedAt: p.published_at
  };
});

await mkdir(dirname(out), { recursive: true });
await writeFile(out, '// Generated by scripts/sync-products.mjs. Do not edit by hand.\nwindow.MONOCHROME_DATA = ' + JSON.stringify({
  syncedAt: new Date().toISOString(),
  store: { name: meta.name, url: meta.url, currency: meta.currency, city: meta.city, province: meta.province, country: meta.country, shipsTo: meta.ships_to_countries },
  collections: collections.map(c => ({ handle: c.handle, title: c.title, count: c.products_count })),
  products
}, null, 1) + ';\n');
console.log(`Wrote ${products.length} products to ${out}`);
